// The two signals, on their own

test('the path conventions are anchored, not substrings', () => {
  assert.equal(isGeneratedPath('src/_generated/schema.gen.ts'), true);
  assert.equal(isGeneratedPath('src/__generated__/types.ts'), true);
  assert.equal(isGeneratedPath('api/generated/client.ts'), true);
  assert.equal(isGeneratedPath('proto/thing_pb2.py'), true);
  assert.equal(isGeneratedPath('proto/thing.pb.go'), true);
  assert.equal(isGeneratedPath('src/schema.gen.ts'), true);

  // The ones a looser rule would have taken with it. Somebody's hand-written reporting
  // module is not a generator's output because the word appears in its name.
  assert.equal(isGeneratedPath('src/generated_reports/summary.ts'), false);
  assert.equal(isGeneratedPath('src/degenerate.ts'), false);
  assert.equal(isGeneratedPath('src/gen.ts'), false);
});

test('a header has to claim generation *and* forbid editing', () => {
  assert.equal(hasGeneratedHeader('// @generated by protoc\nexport const a = 1;'), true);
  assert.equal(hasGeneratedHeader('// Code generated by protoc-gen-go. DO NOT EDIT.\n'), true);
  // The spelling that prompted the issue, which matched neither published convention.
  assert.equal(hasGeneratedHeader('// This file is generated by the x package. Do not edit manually.\n'), true);
  // Half a claim is not a claim: plenty of hand-written files discuss generating things.
  assert.equal(hasGeneratedHeader('// This module has generated reports since 2019.\n'), false);
  assert.equal(hasGeneratedHeader('// Do not edit this without asking Priya first.\n'), false);
  // And it has to be near the top, or every file that mentions it in passing qualifies.
  assert.equal(hasGeneratedHeader('a\nb\nc\nd\ne\nf\n// @generated\n'), false);
});
